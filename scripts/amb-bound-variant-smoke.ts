import assert from "node:assert/strict";
import { parseAmbBridgeConfig } from "../src/lib/amb-bridge-contract.ts";
import { ambBoundInventory, resolveAmbBoundVariant } from "../src/lib/amb-bound-variant.ts";

const binding = { sourceProductId: "supplier-a", color: "WHITE" };
const make = (sku: string, extra = {}) => ({ sourceSkuId: sku, attributes: { Color: "WHITE", Size: "S" }, stock: 2, available: true, ...extra });
const first = make("sku-cn");
const second = make("sku-us");
assert.equal(resolveAmbBoundVariant(binding, "S", [first]), first);
assert.throws(() => resolveAmbBoundVariant(binding, "S", [first, second]));
const explicit = { ...binding, sourceSkuIdsBySize: { S: "sku-cn" } };
assert.equal(resolveAmbBoundVariant(explicit, "S", [first, second]), first);
assert.throws(() => resolveAmbBoundVariant(explicit, "M", [first, second]));
assert.throws(() => resolveAmbBoundVariant({ ...explicit, color: "BLACK" }, "S", [first]));
assert.throws(() => resolveAmbBoundVariant({ ...binding, sourceSkuIdsBySize: { S: "unrelated-product-sku" } }, "S", [first]));
assert.throws(() => resolveAmbBoundVariant(binding, "S", [make("sku", { available: false })]));
assert.throws(() => resolveAmbBoundVariant(binding, "S", [make("sku", { stock: 0 })]));
assert.throws(() => resolveAmbBoundVariant(binding, "S", [make("sku", { stock: null })]));
assert.throws(() => resolveAmbBoundVariant(binding, "S", [first], 3));
assert.throws(() => resolveAmbBoundVariant(binding, "S", [first], 0));
assert.throws(() => resolveAmbBoundVariant(binding, "S", [first], 1.5));
const bag = make("bag-large", { attributes: { Color: "WHITE", Size: "29x23x10cm" } });
assert.equal(resolveAmbBoundVariant({ ...binding, sourceSkuIdsBySize: { "One Size": "bag-large" } }, "One Size", [bag]), bag);
assert.throws(() => resolveAmbBoundVariant(binding, "One Size", [bag, make("bag-small")]));
const parsed = parseAmbBridgeConfig({ ambBridge: { version: 1, products: { dress: explicit, legacy: binding } } });
assert.deepEqual(parsed?.products.dress, explicit);
assert.deepEqual(parsed?.products.legacy, binding);
const shoe = make("shoe-37", { attributes: { Color: "WHITE", "Shoe Size": "37" } });
assert.equal(resolveAmbBoundVariant(binding, "37", [shoe]), shoe);
assert.throws(() => resolveAmbBoundVariant(binding, "38", [shoe]));
assert.equal(ambBoundInventory(explicit, [make("sku-cn", { available: false }), second]).stock, 0);
assert.equal(ambBoundInventory(explicit, [make("sku-cn", { available: false }), second]).available, false);
assert.equal(ambBoundInventory(explicit, [first, second]).stock, 2);
assert.equal(ambBoundInventory(binding, [first, second]).stock, 0);
console.log("AMB EXACT SKU RESOLUTION: PASS (duplicates, wrong identity/color/size, stock, bags, parser compatibility)");
